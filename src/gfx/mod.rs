//! Images: decoding, text-mode rasterising and graphics protocol encoders
//! (kitty placeholders/classic, iTerm2 OSC 1337, sixel).
//!
//! Everything here is pure: functions turn file bytes into pixels, pixels
//! into text cells, and pixels or files into escape-sequence bytes. Nothing
//! writes to the terminal; the stream writer and the pager decide where and
//! when the bytes go. [`decode`] and [`png`] need the `images` feature,
//! [`sixel`] the `sixel` feature; everything else is always built.
//!
//! # From a Markdown image to the screen
//!
//! 1. **Size** from the file header only ([`decode::dimensions`], then
//!    [`size::figure_cells`]), so layout never waits for a decode and a
//!    figure never reflows when its pixels arrive.
//! 2. **Choose** the graphics path once per run with [`select::choose`] and
//!    the block glyphs with [`select::block_glyphs`].
//! 3. **Decode** on a worker thread with [`decode::decode`]: the pixel limit
//!    is enforced before any pixel is allocated, and decoder panics are
//!    caught.
//! 4. **Render** for the chosen path:
//!    * blocks: [`raster::rasterize`] gives a grid of glyph cells;
//!    * kitty placeholders: [`kitty::transmit_placeholder`] once, then
//!      [`kitty::placeholder_row`] is the text of each row;
//!    * kitty classic: [`kitty::transmit`] once, [`kitty::place`] after
//!      every frame;
//!    * iTerm2: [`iterm::inline_image`] of the original file or a PNG
//!      ([`png::encode`]);
//!    * sixel: [`sixel::encode`] of the image composited and scaled to its
//!      cell box with [`resize_onto`].
//!
//! # Redraw rules (plan §7)
//!
//! | Path | Upload | Scrolling, partly visible | Resize, exit |
//! |---|---|---|---|
//! | blocks | none: rows are text | free; rows are cut like text | re-raster |
//! | kitty placeholders | `a=T,U=1` ([`kitty::transmit_placeholder`]); rows show blocks until it is sent | free: rows are text | a new [`kitty::ImageId`] (ids are never reused); `a=d,d=I` on exit |
//! | kitty classic (never in tmux) | `a=t` once ([`kitty::transmit`]) | re-place after each frame ([`kitty::place`], cropped with [`size::visible_pixel_rows`]) | `d=i` when off-screen, `d=I` on exit ([`kitty::delete`]) |
//! | iTerm2 OSC 1337 | none | blocks while scrolling, pixels [`SCROLL_DEBOUNCE`] after the last scroll; a cropped slice when partly visible | redraw |
//! | sixel | none | as iTerm2; crops end on whole sixel bands ([`sixel::crop_rows`]) | redraw |
//!
//! Two rules hold for every kitty command: it carries `q=2`, so the
//! terminal never answers (a late reply would reach the key reader as key
//! presses), and inside tmux it is wrapped chunk by chunk in the passthrough
//! DCS ([`Passthrough::Tmux`]), because tmux turns an unwrapped `ESC _G`
//! into a pane title.

